"""Calibrated confidence scoring engine for the Reusable NLP Asset.

Transforms raw vector similarities and aggregated ranking scores into
interpretable, bounded confidence metrics with categorical ratings
(HIGH, MEDIUM, LOW) and clear explanations.
"""

from __future__ import annotations

import math
from collections.abc import Sequence
from typing import TYPE_CHECKING

from src.week6.schemas import ConfidenceLevel, ConfidenceScore

if TYPE_CHECKING:
    from src.week4.schemas import ResearcherScore


class ConfidenceCalibrator:
    """Calibrates raw scores into standardized, explainable confidence metrics.

    Raw cosine similarities or discounted author scores often sit in narrow,
    non-intuitive numerical ranges (e.g., 0.25–0.65). This calibrator applies
    temperature-scaled logistic calibration, evidence-depth weighting, and
    margin analysis to yield a well-behaved [0.0, 1.0] probability-like metric.
    """

    # Empirical midpoints (mu) and temperatures (tau) per ranking strategy
    _CALIBRATION_PARAMS = {
        "top_k_average_author_discount": {"mu": 0.32, "tau": 0.08},
        "top_k_average": {"mu": 0.48, "tau": 0.10},
        "best_paper": {"mu": 0.52, "tau": 0.10},
        "average": {"mu": 0.45, "tau": 0.09},
        "default": {"mu": 0.45, "tau": 0.10},
    }

    HIGH_THRESHOLD = 0.75
    MEDIUM_THRESHOLD = 0.50

    def __init__(self, strategy: str = "top_k_average_author_discount") -> None:
        self.strategy = strategy
        params = self._CALIBRATION_PARAMS.get(strategy, self._CALIBRATION_PARAMS["default"])
        self.mu = params["mu"]
        self.tau = params["tau"]

    def calibrate(
        self,
        raw_score: float,
        rank: int,
        matched_papers: int,
        next_score: float | None = None,
    ) -> ConfidenceScore:
        """Calculate a calibrated confidence score for a ranked researcher.

        Args:
            raw_score: The numerical score generated by the ranking strategy.
            rank: 1-indexed position of this candidate in the ranking.
            matched_papers: Number of paper hits attributable to this researcher.
            next_score: Score of the candidate ranked immediately after this one (for margin).

        Returns:
            A structured ConfidenceScore containing calibrated value, category,
            margin, and explanation.
        """
        # 1. Base calibration via temperature-scaled logistic function
        z = (raw_score - self.mu) / max(self.tau, 1e-4)
        # Prevent math overflow
        z = max(min(z, 20.0), -20.0)
        base_confidence = 1.0 / (1.0 + math.exp(-z))

        # 2. Score separation margin (evidence of distinct superiority)
        margin = 0.0
        if next_score is not None and next_score <= raw_score:
            margin = raw_score - next_score

        # Small margin boost (up to +0.05 for clear separation at rank 1)
        margin_boost = min(margin * 0.25, 0.05) if rank == 1 else 0.0

        # 3. Evidence depth bonus: reward researchers with robust multi-paper evidence
        evidence_bonus = 0.0
        if matched_papers >= 3:
            evidence_bonus = 0.04
        elif matched_papers >= 2:
            evidence_bonus = 0.02

        # 4. Final blended calibrated score (clamped cleanly to [0.05, 0.98])
        calibrated_score = base_confidence + margin_boost + evidence_bonus
        calibrated_score = max(0.05, min(0.98, calibrated_score))

        # 5. Determine qualitative level
        if calibrated_score >= self.HIGH_THRESHOLD:
            level = ConfidenceLevel.HIGH.value
        elif calibrated_score >= self.MEDIUM_THRESHOLD:
            level = ConfidenceLevel.MEDIUM.value
        else:
            level = ConfidenceLevel.LOW.value

        # 6. Formulate human-readable explanation
        explanation = self._build_explanation(level, raw_score, rank, matched_papers, margin)

        return ConfidenceScore(
            score=calibrated_score,
            level=level,
            raw_score=raw_score,
            margin=margin,
            explanation=explanation,
        )

    def calibrate_ranking(
        self, researcher_scores: Sequence[ResearcherScore]
    ) -> list[ConfidenceScore]:
        """Calibrate a full list of ordered researcher scores together.

        Takes advantage of pairwise score margins across adjacent ranks.
        """
        calibrated: list[ConfidenceScore] = []
        n = len(researcher_scores)
        for i, item in enumerate(researcher_scores):
            next_score = researcher_scores[i + 1].score if (i + 1 < n) else None
            conf = self.calibrate(
                raw_score=item.score,
                rank=i + 1,
                matched_papers=item.matched_papers,
                next_score=next_score,
            )
            calibrated.append(conf)
        return calibrated

    def _build_explanation(
        self,
        level: str,
        raw_score: float,
        rank: int,
        matched_papers: int,
        margin: float,
    ) -> str:
        """Construct a concise, transparent explanation for the assigned confidence."""
        parts = []
        if level == ConfidenceLevel.HIGH.value:
            parts.append("High confidence: strong contextual and semantic match")
        elif level == ConfidenceLevel.MEDIUM.value:
            parts.append("Medium confidence: moderate thematic relevance")
        else:
            parts.append("Low confidence: peripheral or weak semantic overlap")

        if matched_papers > 1:
            parts.append(f"backed by {matched_papers} matching publications")
        else:
            parts.append("based on 1 relevant publication")

        if rank == 1 and margin >= 0.05:
            parts.append(f"with clear score lead (+{margin:.2f})")

        return "; ".join(parts) + "."
